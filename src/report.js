// Exports: Markdown incident report, CSV timeline, JSON alerts, ATT&CK Navigator layer.

const md = (s) => String(s ?? "").replace(/([\\`*_[\]|<>])/g, "\\$1");
const ICON = { critical: "🟥", high: "🟧", medium: "🟨", low: "🟦", info: "⬜" };

export function toMarkdown(r) {
  const L = [];
  L.push(`# Windows incident report${r.filename ? `: ${md(r.filename)}` : ""}`, "");
  L.push(`**Verdict:** ${r.verdict.label} · **Risk score:** ${r.score}/100 · ${r.stats.events} events from ${r.stats.hosts} host(s) · ${md(r.stats.first)} → ${md(r.stats.last)}`, "");
  L.push(`> ${md(r.summary)}`, "");
  if (r.story.length) {
    L.push("## What happened", "");
    for (const s of r.story) L.push(`- **${s.time.slice(0, 19).replace("T", " ")}** · ${md(s.host)}: the attacker ${md(s.text)}`);
    L.push("");
  }
  if (r.alerts.length) {
    L.push("## Detections", "");
    for (const a of [...r.alerts].sort((x, y) => ["critical", "high", "medium", "low"].indexOf(x.severity) - ["critical", "high", "medium", "low"].indexOf(y.severity))) {
      L.push(`### ${ICON[a.severity]} ${a.severity.toUpperCase()}: ${md(a.title)}`, "");
      L.push(`${md(a.time)} · host ${md(a.host)}${a.user ? ` · user ${md(a.user)}` : ""}${a.ip ? ` · source ${md(a.ip)}` : ""}${a.count > 1 ? ` · ${a.count} occurrences` : ""}`, "");
      if (a.techniques.length) L.push(`ATT&CK: ${a.techniques.map((t) => `[${t.id} ${t.name}](${t.url})`).join(", ")}`, "");
      if (a.detail) L.push("```", String(a.detail).replace(/```/g, "'''"), "```", "");
      if (a.decoded) L.push("Decoded command:", "```", a.decoded.replace(/```/g, "'''"), "```", "");
    }
  }
  if (r.mitre.length) {
    L.push("## MITRE ATT&CK", "", "| Tactic | Technique |", "|---|---|");
    for (const t of r.mitre) L.push(`| ${t.tactic} | [${t.id}](${t.url}) ${md(t.name)} |`);
    L.push("");
  }
  const ips = r.entities.ips.filter((i) => i.alerts || i.failures >= 5);
  const users = r.entities.users.filter((u) => u.alerts);
  if (ips.length || users.length) {
    L.push("## Indicators", "");
    for (const i of ips) L.push(`- IP ${md(i.name)}${i.public ? " (internet)" : ""}: ${i.failures} failed / ${i.logons} successful logons, ${i.alerts} alert(s)`);
    for (const u of users) L.push(`- Account ${md(u.name)}: ${u.alerts} alert(s)`);
    L.push("");
  }
  L.push("## Recommended actions", "");
  for (const x of r.recommendations) L.push(`- ${md(x)}`);
  L.push("", `_Generated by ${r.tool.name} ${r.tool.version} on ${r.analyzedAt}._`, "");
  return L.join("\n");
}

const csvCell = (v) => {
  let s = String(v ?? "");
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s; // formula-injection guard for Excel
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function toTimelineCsv(r, { notableOnly = false } = {}) {
  const rows = [["time", "host", "event_id", "channel", "category", "title", "detail", "user", "ip", "notable"]];
  for (const t of r.timeline) {
    if (notableOnly && !t.notable) continue;
    rows.push([t.time, t.host, t.id, t.channel, t.category, t.title, t.detail, t.actor, t.ip, t.notable ? "yes" : ""]);
  }
  return rows.map((x) => x.map(csvCell).join(",")).join("\n") + "\n";
}

export function toAlertsJson(r) {
  return JSON.stringify(r.alerts.map(({ key, ...a }) => a), null, 2);
}

// Layer file for https://mitre-attack.github.io/attack-navigator/
export function toNavigatorLayer(r) {
  const color = { critical: "#e5484d", high: "#f76b15", medium: "#ffc53d", low: "#3e63dd" };
  const best = new Map();
  for (const a of r.alerts) {
    for (const t of a.mitre) {
      const cur = best.get(t);
      if (!cur || ["critical", "high", "medium", "low"].indexOf(a.severity) < ["critical", "high", "medium", "low"].indexOf(cur.severity)) best.set(t, a);
    }
  }
  return JSON.stringify({
    name: `WinTrace: ${r.filename || "analysis"}`,
    versions: { attack: "16", navigator: "5.1.0", layer: "4.5" },
    domain: "enterprise-attack",
    description: r.summary,
    techniques: [...best].map(([id, a]) => ({ techniqueID: id, color: color[a.severity], comment: a.title, enabled: true, score: { critical: 100, high: 75, medium: 50, low: 25 }[a.severity] })),
    gradient: { colors: ["#ffffff", "#e5484d"], minValue: 0, maxValue: 100 },
  }, null, 2);
}
